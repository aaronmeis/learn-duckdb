def render_json_record(text):
    d = json.loads(text)

    def row(k, v):
        v = "<pre>" + html.escape(json.dumps(v, indent=2, ensure_ascii=False)) + "</pre>" if isinstance(v, (dict, list)) else html.escape(str(v))
        return f"<tr><th>{html.escape(str(k))}</th><td>{v}</td></tr>"
    body = "<table><tbody>" + "".join(row(k, v) for k, v in d.items()) + "</tbody></table>"
    return {"description": "Machine-readable record of the NotebookLM W8 run for this pack."}, body


def render_code(text):
    return {"description": "The script that ran the NotebookLM W8 suite for this pack."}, f"<pre><code>{html.escape(text)}</code></pre>"


def render_diagram_sources(folder):
    h = "<p>Each diagram as the rendered PNG, the editable draw.io file, and the Mermaid source where one exists. Open .drawio files in draw.io (desktop, or app.diagrams.net).</p>"
    for png in sorted(folder.glob("*.png")):
        stem = png.stem
        links = [f'<a href="../assets/diagrams/{png.name}" target="_blank">PNG</a>']
        if (folder / f"{stem}.drawio").exists():
            links.append(f'<a href="../assets/diagrams/{stem}.drawio" download>draw.io</a>')
        mmd = folder / f"{stem}.mmd"
        if mmd.exists():
            links.append(f'<a href="../assets/diagrams/{stem}.mmd" download>Mermaid (.mmd)</a>')
        h += f"<h2>{html.escape(stem)}</h2><p>{' · '.join(links)}</p>"
        h += f'<a href="../assets/diagrams/{png.name}" target="_blank"><img class="embed" src="../assets/diagrams/{png.name}" alt="{html.escape(stem)}" loading="lazy"></a>'
        if mmd.exists():
            src = html.escape(mmd.read_text(encoding="utf-8"))
            h += f'<details><summary>Mermaid source</summary><pre>{src}</pre></details>'
    return {"description": "Rendered diagrams with their editable draw.io and Mermaid sources."}, h


