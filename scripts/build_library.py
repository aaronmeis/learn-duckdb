def main():
    LIB.mkdir(exist_ok=True)
    manifest = []
    for idx, (slug, path, section, title, nblm) in enumerate(PAGES):
        if path.is_dir():
            fm, body = render_diagram_sources(path)
        else:
            text = path.read_text(encoding="utf-8-sig")
            if path.suffix == ".csv":
                fm, body = render_csv(text)
            elif path.name == "cut-script.json":
                fm, body = render_cut_script(text)
            elif path.name == "shorts-topics.json":
                fm, body = render_shorts_plan(text)
            elif path.name.endswith("__notebooklm.json"):
                fm, body = render_json_record(text)
            elif path.suffix == ".json":
                fm, body = render_mindmap_json(text)
            elif path.suffix == ".ps1":
                fm, body = render_code(text)
            else:
                fm, body = render_md(text)
        h1 = re.search(r"<h1>(.*?)</h1>", body)
        page_title = title or (re.sub("<.*?>", "", h1.group(1)) if h1 else path.stem)
        if h1 and not title:
            body = body.replace(h1.group(0), "", 1)
        desc = str(fm.get("description", "")) if fm else ""
        caveat = f'<div class="callout warning"><div class="callout-title">NotebookLM output — read with the vault views</div><p>{link_citations(html.escape(NBLM_CAVEAT))}</p></div>' if nblm else ""
        prev_ = PAGES[idx - 1] if idx > 0 and PAGES[idx - 1][2] == section else None
        next_ = PAGES[idx + 1] if idx + 1 < len(PAGES) and PAGES[idx + 1][2] == section else None
        pn = ""
        if prev_ or next_:
            pn = '<div class="prevnext">' + (f'<a href="{prev_[0]}.html">&larr; Previous</a>' if prev_ else "<span></span>") + \
                 (f'<a href="{next_[0]}.html">Next &rarr;</a>' if next_ else "<span></span>") + "</div>"
        src_rel = str(path.relative_to(PACK.parent.parent.parent)) if PACK.parent.parent.parent in path.parents else str(path)
        (LIB / f"{slug}.html").write_text(PAGE_TMPL.format(
            title=html.escape(page_title), desc=html.escape(desc), section=html.escape(section),
            descblock=f'<p class="lead">{html.escape(desc)}</p>' if desc else "", caveat=caveat,
            body=body, source=html.escape(src_rel), prevnext=pn), encoding="utf-8")
        manifest.append({"slug": slug, "title": page_title, "section": section, "desc": desc, "nblm": nblm})

    sections = {}
    for m in manifest:
        sections.setdefault(m["section"], []).append(m)
    idx_body = ""
    for sec, items in sections.items():
        idx_body += f"<h2>{html.escape(sec)}</h2><ul class='pagelist'>" + "".join(
            f'<li><a href="{m["slug"]}.html">{html.escape(m["title"])}</a>' +
            (f' <span class="muted">— {html.escape(m["desc"])}</span>' if m["desc"] else "") + "</li>" for m in items) + "</ul>"
    (LIB / "index.html").write_text(PAGE_TMPL.format(
        title="Library", desc="Every Purview study note rendered as a web page.", section="Index",
        descblock=f'<p class="lead">{len(manifest)} pages rendered from the Obsidian deep-dive pack and the NotebookLM exports.</p>',
        caveat="", body=idx_body, source="Learning/tech-deep-dive/microsoft-purview/", prevnext=""), encoding="utf-8")
    (LIB / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    (LIB / "manifest.js").write_text("window.LIBRARY = " + json.dumps(manifest) + ";\n", encoding="utf-8")
    print(f"built {len(manifest)} pages + index; {len(SOURCES)} sources linked")


if __name__ == "__main__":
    main()
